func TestDispatchReceiptAggregationPreservesFailures(t *testing.T) {
	root := t.TempDir()
	paths := []string{filepath.Join(root, "dispatch-0001"), filepath.Join(root, "dispatch-0002")}
	for _, p := range paths {
		if err := os.Mkdir(p, 0700); err != nil {
			t.Fatal(err)
		}
	}
	cost := 0.25
	input, output, cached, reasoning := 100, 10, 80, 4
	receipt := Receipt{ID: "same-request", Provider: "synthetic", Cost: &cost, Prompt: &input, Output: &output, Cached: &cached, Reasoning: &reasoning}
	for i, p := range paths {
		if err := writeJSON(filepath.Join(p, "provider-ledger.json"), ReceiptLedger{SchemaVersion: 1, Complete: i == 1, Generations: []Receipt{receipt}}); err != nil {
			t.Fatal(err)
		}
	}
	if err := aggregateDispatchLedgers(root, paths); err == nil {
		t.Fatal("failed dispatch became complete coverage")
	}
	var got ReceiptLedger
	if err := readJSON(filepath.Join(root, "provider-ledger.json"), &got); err != nil {
		t.Fatal(err)
	}
	if got.Complete || got.Cost != nil || got.KnownCost != 0.25 || got.KnownTokens != 110 || len(got.Generations) != 1 {
		t.Fatalf("dispatch receipts doubled/dropped: %+v", got)
	}
	receipt.Model = "conflicting"
	if err := writeJSON(filepath.Join(paths[1], "provider-ledger.json"), ReceiptLedger{SchemaVersion: 1, Complete: true, Generations: []Receipt{receipt}}); err != nil {
		t.Fatal(err)
	}
	if err := aggregateDispatchLedgers(root, paths); err == nil {
		t.Fatal("conflicting request accepted")
	}
}

