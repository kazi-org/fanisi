func TestKaziEvaluationLifecycle(t *testing.T) {
	for _, mode := range []string{"success", "two", "third", "context", "hidden", "hidden-skip", "mode", "symlink", "artifact-mode", "ignored", "instruction", "protected", "no-worker", "timeout"} {
		t.Run(mode, func(t *testing.T) {
			e, path := kaziFixture(t, mode)
			started := time.Now()
			err := evalRun(context.Background(), path, "kazi-claude", 1)
			dir := filepath.Join(e.Output, e.TaskID, "kazi-claude", "1")
			var attempt Attempt
			if readErr := readJSON(filepath.Join(dir, "attempt.json"), &attempt); readErr != nil {
				t.Fatal(readErr)
			}
			good := mode == "success" || mode == "two"
			if good && (err != nil || attempt.Status != "verified_pending_review" || !attempt.ScopeOK || !attempt.VerificationPassed) {
				t.Fatalf("expected independently verified attempt: %+v %v", attempt, err)
			}
			if !good && (err == nil || attempt.Status == "verified_pending_review") {
				t.Fatalf("invalid run became verified: %+v %v", attempt, err)
			}
			if mode == "timeout" && time.Since(started) > 8*time.Second {
				t.Fatal("controller deadline did not terminate descendants")
			}
			if good {
				var m DispatchManifest
				if err := readJSON(filepath.Join(dir, "dispatch-manifest.json"), &m); err != nil {
					t.Fatal(err)
				}
				count := 1
				if mode == "two" {
					count = 2
				}
				if len(m.Dispatches) != count {
					t.Fatalf("dispatches: %+v", m)
				}
				turns, cost := 0, 0.0
				for _, d := range m.Dispatches {
					turns += d.ReservedTurns
					cost += d.ReservedCost
				}
				if turns > 5 || cost > 2 {
					t.Fatalf("allowance reset: %+v", m)
				}
				if mode == "two" && m.Dispatches[0].Error == "" {
					t.Fatal("failed first dispatch omitted")
				}
				patch, err := os.ReadFile(filepath.Join(dir, "candidate.patch"))
				if err != nil {
					t.Fatal(err)
				}
				if strings.Contains(string(patch), ".kazi") || strings.Contains(string(patch), ".mcp") {
					t.Fatal("controller artifacts contaminated candidate")
				}
				var artifacts ControllerArtifactManifest
				if err := readJSON(filepath.Join(dir, "controller-artifacts.json"), &artifacts); err != nil {
					t.Fatal(err)
				}
				if artifacts.WorkspaceBase != e.Base || len(artifacts.Artifacts) != 2 {
					t.Fatalf("artifact evidence: %+v", artifacts)
				}
				if err := recordReview(context.Background(), dir, "accept", "independent-fixture", "agent", 1, "checked synthetic change"); err != nil {
					t.Fatal(err)
				}
			}
		})
	}
}

